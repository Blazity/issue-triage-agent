import { describe, expect, test } from "bun:test";

import {
  admitIssueSignal,
  createInMemoryAdmissionStore,
} from "../src/admission";
import type { IssueSignal } from "../src/domain";

function issue(overrides: Partial<IssueSignal> = {}): IssueSignal {
  return {
    source: "webhook",
    sourceAccount: "acme",
    sourceEventId: "delivery-1",
    routingKeys: ["checkout"],
    title: "Checkout is failing",
    description: "Customers cannot pay.",
    occurredAt: "2026-08-06T10:00:00.000Z",
    ...overrides,
  };
}

describe("admitIssueSignal", () => {
  test("accepts an event once and returns the original signal for a duplicate", async () => {
    const store = createInMemoryAdmissionStore();
    const first = await admitIssueSignal(issue(), ["storefront"], store, {
      now: new Date("2026-08-06T10:00:00.000Z"),
      sourceEventsPerMinute: 60,
    });
    const duplicate = await admitIssueSignal(issue(), ["storefront"], store, {
      now: new Date("2026-08-06T10:00:05.000Z"),
      sourceEventsPerMinute: 60,
    });

    expect(first.status).toBe("accepted");

    if (first.status !== "accepted") {
      throw new Error("Expected accepted admission");
    }

    expect(duplicate).toEqual({
      status: "duplicate",
      signalId: first.signalId,
    });
  });

  test("stops events generated by this agent before creating another run", async () => {
    const result = await admitIssueSignal(
      issue({ origin: { generatedBy: "issue-triage-agent", runDepth: 1 } }),
      ["storefront"],
      createInMemoryAdmissionStore(),
      { now: new Date("2026-08-06T10:00:00.000Z"), sourceEventsPerMinute: 60 },
    );

    expect(result).toEqual({ status: "ignored", reason: "recursive_event" });
  });

  test("admits an unmapped issue for an explicit human handoff", async () => {
    const store = createInMemoryAdmissionStore();
    const result = await admitIssueSignal(issue(), [], store, {
      now: new Date("2026-08-06T10:00:00.000Z"),
      sourceEventsPerMinute: 60,
    });

    expect(result.status).toBe("accepted");

    if (result.status !== "accepted") {
      throw new Error("Expected accepted admission");
    }

    expect(await store.getSignal(result.signalId)).toMatchObject({
      repositoryKeys: [],
    });
  });

  test("suppresses authenticated source bursts without starting more work", async () => {
    const store = createInMemoryAdmissionStore();
    const options = {
      now: new Date("2026-08-06T10:00:00.000Z"),
      sourceEventsPerMinute: 1,
    };

    await admitIssueSignal(issue(), ["storefront"], store, options);
    const suppressed = await admitIssueSignal(
      issue({ sourceEventId: "delivery-2", title: "Search is failing" }),
      ["storefront"],
      store,
      options,
    );

    expect(suppressed).toEqual({
      status: "suppressed",
      reason: "source_rate_limit",
    });
  });

  test("deduplicates distinct deliveries that describe the same routed incident", async () => {
    const store = createInMemoryAdmissionStore();
    const first = await admitIssueSignal(issue(), ["storefront"], store, {
      now: new Date("2026-08-06T10:00:00.000Z"),
      sourceEventsPerMinute: 60,
    });
    const duplicate = await admitIssueSignal(
      issue({ sourceEventId: "delivery-2", title: "  CHECKOUT   IS FAILING " }),
      ["storefront"],
      store,
      {
        now: new Date("2026-08-06T10:01:00.000Z"),
        sourceEventsPerMinute: 60,
      },
    );

    expect(first.status).toBe("accepted");

    if (first.status !== "accepted") {
      throw new Error("Expected accepted admission");
    }

    expect(duplicate).toEqual({
      status: "duplicate",
      signalId: first.signalId,
    });
  });

  test("fences the entire incident before repository work begins", async () => {
    const store = createInMemoryAdmissionStore();
    const admitted = await admitIssueSignal(
      issue(),
      ["storefront", "api"],
      store,
      {
        now: new Date("2026-08-06T10:00:00.000Z"),
        sourceEventsPerMinute: 60,
      },
    );

    if (admitted.status !== "accepted") {
      throw new Error("Expected accepted admission");
    }

    const deadline = new Date(Date.now() + 60_000);
    const owner = await store.claimIncidentRun(
      admitted.signalId,
      "workflow-1",
      deadline,
    );
    const competitor = await store.claimIncidentRun(
      admitted.signalId,
      "workflow-2",
      deadline,
    );

    expect(owner.status).toBe("claimed");
    expect(competitor).toEqual({ status: "owned", retryAt: deadline });

    if (owner.status !== "claimed") {
      throw new Error("Expected incident ownership");
    }

    expect(
      await store.saveIncidentOutcomes(
        admitted.signalId,
        "workflow-2",
        owner.fencingToken,
        [],
      ),
    ).toBe(false);
    expect(
      await store.saveIncidentOutcomes(
        admitted.signalId,
        "workflow-1",
        owner.fencingToken,
        [],
      ),
    ).toBe(true);
    expect(
      await store.claimIncidentRun(admitted.signalId, "workflow-2", deadline),
    ).toEqual({ status: "completed" });
  });
});
